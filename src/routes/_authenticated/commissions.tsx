import { createFileRoute, useNavigate } from "@tanstack/react-router";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { useMemo } from "react";
import { Download, Search } from "lucide-react";

import { AppShell } from "@/components/app-shell";
import { PortalGuard } from "@/components/partner/portal-guard";
import { PortalPageHeader } from "@/components/partner/page-header";
import { PartnerKpiCard } from "@/components/partner/kpi-card";
import {
  CommissionList,
  exportCommissionsCsv,
  type CommissionRow,
} from "@/components/partner/commission-table";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { usePortalIdentity } from "@/hooks/use-portal-identity";
import { supabase } from "@/integrations/supabase/client";
import { COMMISSION_STATUS, currency, type CommissionStatus } from "@/lib/partner-portal";
import { titleCaseName } from "@/lib/text";

type RangeKey = "all" | "month" | "year";

interface CommissionSearch {
  status?: string;
  org?: string;
  q?: string;
  range?: string;
}

export const Route = createFileRoute("/_authenticated/commissions")({
  head: () => ({
    meta: [
      { title: "Partner Commissions — Magenta Portal" },
      {
        name: "description",
        content:
          "Internal view of every partner commission generated by funded applications, with overrides, bulk payment runs and export.",
      },
      { property: "og:title", content: "Partner Commissions — Magenta Portal" },
      { property: "og:description", content: "Approve, pay and export partner commissions." },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary" },
      { name: "robots", content: "noindex" },
    ],
  }),
  validateSearch: (search: Record<string, unknown>): CommissionSearch => ({
    ...(typeof search['status'] === "string" ? { status: search['status'] } : {}),
    ...(typeof search['org'] === "string" ? { org: search['org'] } : {}),
    ...(typeof search['q'] === "string" ? { q: search['q'] } : {}),
    ...(typeof search['range'] === "string" ? { range: search['range'] } : {}),
  }),
  component: () => (
    <PortalGuard audience="internal">
      <InternalCommissions />
    </PortalGuard>
  ),
});

function InternalCommissions() {
  const { data: identity } = usePortalIdentity();
  const queryClient = useQueryClient();
  const navigate = useNavigate({ from: "/commissions" });
  const search = Route.useSearch();

  const statusFilter = (
    search.status && search.status in COMMISSION_STATUS ? search.status : "all"
  ) as "all" | CommissionStatus;
  const orgFilter = search.org ?? "all";
  const query = search.q ?? "";
  const range: RangeKey = (["month", "year"] as string[]).includes(search.range ?? "")
    ? (search.range as RangeKey)
    : "all";

  const setFilter = (patch: CommissionSearch) => {
    void navigate({
      search: (prev) => {
        const next = { ...prev, ...patch } as Record<string, string | undefined>;
        for (const key of Object.keys(next)) {
          const value = next[key];
          if (!value || value === "all") delete next[key];
        }
        return next as CommissionSearch;
      },
      replace: true,
    });
  };

  const { data, isLoading } = useQuery({
    queryKey: ["internal-commissions"],
    queryFn: async () => {
      const [rows, orgs] = await Promise.all([
        supabase
          .from("partner_commissions")
          .select(
            "id, amount, rate_percent, funded_amount, status, paid_at, payment_reference, note, organization_id, application_id, application:partner_applications(reference, legal_business_name)",
          )
          .order("created_at", { ascending: false }),
        supabase.from("partner_organizations").select("id, name").order("name"),
      ]);
      if (rows.error) throw new Error(rows.error.message);
      return { rows: (rows.data ?? []) as unknown as CommissionRow[], orgs: orgs.data ?? [] };
    },
  });

  const refresh = async () => {
    await queryClient.invalidateQueries({ queryKey: ["internal-commissions"] });
  };

  const orgNameMap = useMemo(
    () => new Map((data?.orgs ?? []).map((o) => [o.id, o.name])),
    [data?.orgs],
  );
  const orgName = (id: string) => orgNameMap.get(id) ?? "";

  const all = data?.rows ?? [];

  /** Only organizations that actually have commissions are worth filtering by. */
  const orgOptions = useMemo(() => {
    const ids = new Set(all.map((r) => r.organization_id));
    return (data?.orgs ?? [])
      .filter((o) => ids.has(o.id))
      .map((o) => ({ id: o.id, name: titleCaseName(o.name) }));
  }, [all, data?.orgs]);

  const rows = useMemo(() => {
    const now = new Date();
    const q = query.trim().toLowerCase();
    return all.filter((r) => {
      if (statusFilter !== "all" && r.status !== statusFilter) return false;
      if (orgFilter !== "all" && r.organization_id !== orgFilter) return false;
      if (range !== "all") {
        if (!r.paid_at) return false;
        const paid = new Date(r.paid_at);
        if (paid.getFullYear() !== now.getFullYear()) return false;
        if (range === "month" && paid.getMonth() !== now.getMonth()) return false;
      }
      if (q) {
        const haystack = [
          orgName(r.organization_id),
          r.application?.legal_business_name ?? "",
          r.application?.reference ?? "",
          r.payment_reference ?? "",
        ]
          .join(" ")
          .toLowerCase();
        if (!haystack.includes(q)) return false;
      }
      return true;
    });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [all, statusFilter, orgFilter, query, range, orgNameMap]);

  const sum = (list: CommissionRow[], status: CommissionStatus) =>
    list.filter((r) => r.status === status).reduce((s, r) => s + Number(r.amount ?? 0), 0);

  const filtersActive =
    statusFilter !== "all" || orgFilter !== "all" || range !== "all" || query.trim() !== "";

  return (
    <AppShell>
      <PortalPageHeader
        title="Partner Commissions"
        subtitle="Commissions are created automatically the moment an application is marked funded."
        actions={
          <Button
            variant="secondary"
            onClick={() => exportCommissionsCsv(rows, "partner-commissions", orgName)}
            disabled={rows.length === 0}
          >
            <Download className="h-4 w-4" aria-hidden="true" /> Export CSV
          </Button>
        }
      />

      <section aria-label="Totals" className="grid gap-3 sm:grid-cols-3">
        <PartnerKpiCard
          label="Pending"
          value={currency(sum(rows, "pending"))}
          tone="gold"
          loading={isLoading}
        />
        <PartnerKpiCard
          label="Approved"
          value={currency(sum(rows, "approved"))}
          tone="brand"
          loading={isLoading}
        />
        <PartnerKpiCard
          label="Paid"
          value={currency(sum(rows, "paid"))}
          tone="success"
          loading={isLoading}
        />
      </section>

      <div className="mt-6 flex flex-wrap items-center gap-3">
        <div className="relative min-w-[15rem] flex-1">
          <Search
            className="pointer-events-none absolute top-1/2 left-3 h-4 w-4 -translate-y-1/2 text-muted-foreground"
            aria-hidden="true"
          />
          <Input
            className="pl-9"
            value={query}
            onChange={(e) => setFilter({ q: e.target.value })}
            placeholder="Search business, reference or payment run"
            aria-label="Search commissions"
          />
        </div>

        <select
          aria-label="Filter by partner organization"
          className="focus-ring h-10 rounded-md border border-input bg-card px-3 text-sm"
          value={orgFilter}
          onChange={(e) => setFilter({ org: e.target.value })}
        >
          <option value="all">All Partners</option>
          {orgOptions.map((o) => (
            <option key={o.id} value={o.id}>
              {o.name}
            </option>
          ))}
        </select>

        <select
          aria-label="Filter by commission status"
          className="focus-ring h-10 rounded-md border border-input bg-card px-3 text-sm"
          value={statusFilter}
          onChange={(e) => setFilter({ status: e.target.value })}
        >
          <option value="all">All Statuses</option>
          {(Object.keys(COMMISSION_STATUS) as CommissionStatus[]).map((s) => (
            <option key={s} value={s}>
              {COMMISSION_STATUS[s].label}
            </option>
          ))}
        </select>

        <select
          aria-label="Filter by paid date"
          className="focus-ring h-10 rounded-md border border-input bg-card px-3 text-sm"
          value={range}
          onChange={(e) => setFilter({ range: e.target.value })}
        >
          <option value="all">Any Date</option>
          <option value="month">Paid This Month</option>
          <option value="year">Paid This Year</option>
        </select>

        {filtersActive ? (
          <Button
            variant="ghost"
            size="sm"
            onClick={() => setFilter({ status: "all", org: "all", q: "", range: "all" })}
          >
            Clear Filters
          </Button>
        ) : null}
      </div>

      <p className="mt-3 text-xs text-muted-foreground">
        {isLoading ? "Loading…" : `Showing ${rows.length} of ${all.length} commissions`}
      </p>

      <div className="mt-5">
        <CommissionList
          key={`${statusFilter}-${orgFilter}-${range}-${query}`}
          rows={rows}
          loading={isLoading}
          isAdmin={Boolean(identity?.isAdmin)}
          orgName={orgName}
          linkOrganization
          enableBulk
          onRefresh={refresh}
        />
      </div>
    </AppShell>
  );
}
